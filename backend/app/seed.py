def seed_games(db: Session) -> None:
    for game_data in SEED_GAMES:
        game = db.scalar(select(Game).where(Game.slug == game_data["slug"]))
        if game is None:
            db.add(Game(**game_data))
            continue

        for key, value in game_data.items():
            setattr(game, key, value)

    db.commit()
